import type { Foundation, ScaffoldReport, TicketProposal, Vision } from '../../../../shared/api';
import { Card, Pill, Table } from '../../ui/primitives';

// The founding artifacts as cards — in the checkpoints of the New project page and in the conversation where the agent posted them.

const List = ({ label, xs }: { label: string; xs: string[] }) => (xs.length ? <><div className="label">{label}</div><ul className="rc-list">{xs.map((x, i) => <li key={i}>{x}</li>)}</ul></> : null);

export function VisionCard({ v, name = '', tickets = [] }: { v: Vision; name?: string; tickets?: TicketProposal[] }) {
  return (
    <Card className="plan">
      <div className="plan-head"><Pill tone="info">Vision</Pill><strong>{v.name || name}</strong></div>
      <p className="pre-wrap"><strong>{v.pitch}</strong></p>
      <List label="For" xs={v.users} />
      {v.problem ? <><div className="label">The problem</div><p className="pre-wrap">{v.problem}</p></> : null}
      {v.today ? <><div className="label">Today</div><p className="pre-wrap">{v.today}</p></> : null}
      <List label="The first version" xs={v.firstVersion} />
      <List label="Later" xs={v.later} />
      {v.success ? <><div className="label">Success</div><p className="pre-wrap">{v.success}</p></> : null}
      <List label="Constraints" xs={v.constraints} />
      {tickets.length ? <List label={`The first version's tickets (${tickets.length}) — filed in the backlog when the project is ready`} xs={tickets.map((t) => `${t.title}${t.size !== '?' ? ` · ${t.size}` : ''}`)} /> : null}
    </Card>
  );
}

export function FoundationCard({ p }: { p: Foundation }) {
  return (
    <Card className="plan">
      <div className="plan-head"><Pill tone="info">Foundations</Pill>{p.basedOn ? <span className="muted">{`following ${p.basedOn}`}</span> : null}</div>
      <p className="pre-wrap">{p.summary}</p>
      <Table head={['Surface', 'Stack', 'Generated by', 'Checks']}>
        {p.surfaces.map((s) => (
          <tr key={s.key}><td><div className="mono">{s.key}</div><div className="muted mono">{s.path}/</div></td><td>{s.stack}</td>
            <td className="mono">{s.generate ?? '— (a plain folder)'}</td><td className="mono">{[s.test, s.lint, s.build].filter(Boolean).join(' · ')}</td></tr>
        ))}
      </Table>
      <div className="kv">
        {p.data ? <><span className="label">Data</span><span>{p.data}</span></> : null}
        {p.auth ? <><span className="label">Auth</span><span>{p.auth}</span></> : null}
        {p.hosting ? <><span className="label">Hosting</span><span>{p.hosting}</span></> : null}
        {p.ci ? <><span className="label">CI</span><span>{p.ci}</span></> : null}
        {p.devCommand ? <><span className="label">Run it</span><span className="mono">{p.devCommand}</span></> : null}
        {p.skeleton ? <><span className="label">Skeleton proves</span><span>{p.skeleton}</span></> : null}
      </div>
      <List label="Conventions from day one" xs={p.conventions} />
      <List label="Decided together" xs={p.decisions} />
      <List label="Assumed without asking — veto any" xs={p.assumptions} />
      <List label="Still open" xs={p.questions} />
    </Card>
  );
}

export function ScaffoldCard({ r }: { r: ScaffoldReport }) {
  return (
    <Card className="plan">
      <div className="plan-head"><Pill tone={r.status === 'ok' ? 'ok' : 'bad'}>{`Skeleton ${r.status}`}</Pill>{r.devCommand ? <span className="mono">{r.devCommand}</span> : null}</div>
      {r.checks.length ? <ul className="rc-list">{r.checks.map((c, i) => <li key={i} className={c.ok ? 'add' : 'error'}>{`${c.ok ? '✓' : '✗'} `}<span className="mono">{c.command}</span>{c.note ? <span className="muted">{` — ${c.note}`}</span> : null}</li>)}</ul> : null}
      <List label="Assumed" xs={r.assumptions} />
      {r.notes ? <p className="pre-wrap muted">{r.notes}</p> : null}
    </Card>
  );
}

