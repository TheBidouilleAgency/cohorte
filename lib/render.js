'use strict';
// cohorte — render the core prompts for Claude Code.
//
// The sources in core/commands/*.md and core/agents/*.md are written with a handful of
// path tokens (`<core>`, `<state>`, `<agents>`, …) so the prose never hardcodes where a
// machine keeps things. Rendering prepends one preamble that resolves every token, keeps
// only the frontmatter keys Claude Code understands (an unknown key is prose the model
// reads as an instruction), and leaves the body untouched.
//
// 3.0.0 made Claude Code the only target and dropped the capability conditionals that served
// the other coding agents: the last multi-runtime tree is on the `archive/multi-runtime` branch.

const os = require('os');
const path = require('path');

const COMMAND_KEYS = ['model', 'description', 'argument-hint', 'allowed-tools', 'disable-model-invocation'];
const AGENT_KEYS = ['name', 'description', 'tools', 'model'];

// The matcher the project hook is registered with. `Agent` is the subagent tool's name
// since Claude Code 2.1.63; `Task` is its former name, kept so an older client still
// delivers dispatches to the preflight phase gate.
const GATE_MATCHER = 'Bash|Task|Agent';

// Path as the human/model should see it: `~/…` reads better than an expanded homedir,
// and a project-relative path must stay relative (the agent's cwd is the repo).
function displayPath(p) {
  if (!p) return null;
  const home = os.homedir();
  if (p === home) return '~';
  if (p.startsWith(home + path.sep)) return '~/' + path.relative(home, p).split(path.sep).join('/');
  return p.split(path.sep).join('/');
}

// A path a shell will expand even inside double quotes: `$HOME/…` rather than `~/…`.
function shellPath(p) {
  const home = os.homedir();
  if (p.startsWith(home + path.sep)) return '$HOME/' + path.relative(home, p).split(path.sep).join('/');
  return p.split(path.sep).join('/');
}

/**
 * The machine layout every rendered file is written against.
 * @param {string} globalDir  Claude Code's config dir (~/.claude, or $CLAUDE_CONFIG_DIR)
 */
function layout(globalDir) {
  const core = path.join(globalDir, 'cohorte');
  return {
    globalDir,
    core,
    commands: path.join(globalDir, 'commands'),
    fixedAgents: path.join(globalDir, 'agents'),
    workflows: path.join(globalDir, 'workflows'),
    config: path.join(globalDir, 'cohorte.config.yaml'),
    projectLib: path.join(core, 'lib', 'project.js'),
  };
}

function preamble(L, { kind = 'command' } = {}) {
  const core = displayPath(L.core);
  const sync = `node "${shellPath(L.projectLib)}" sync .`;
  const out = [];
  out.push(`> **Cohorte — Claude Code.** Generated by the cohorte installer — do not edit this file;`);
  out.push(`> edit \`core/${kind === 'agent' ? 'agents' : 'commands'}/\` in the cohorte source and re-install.`);
  out.push('>');
  out.push(`> - \`<core>\` = \`${core}\` — the pipeline's shared, machine-wide assets (\`pipeline/scripts/\`, \`pipeline/schema/<topic>.md\` — read only the one a step cites, \`templates/\`). Every \`<core>/…\` path below resolves there, and nowhere else.`);
  out.push('> - `<state>` = `.claude/` in **this repo** — what the pipeline generates for this project (`gate-config.json`, `preflight.ok`, `pipeline-metrics.jsonl`, `pipeline.json`, `profile.json` — the parsed `PIPELINE.md` machine block).');
  out.push('> - `<memory>` = `CLAUDE.md` — the project-instructions file at the repo root, loaded into every session here.');
  out.push(`> - \`<config>\` = \`${displayPath(L.config)}\` — your user-level config (kanban boards, shared vault). One per human, never committed.`);
  out.push('> - `<agents>` = `.claude/agents` in **this repo** — the surface agents rendered from `PIPELINE.md`, committed with the code. Never write a surface agent anywhere else.');
  out.push(`> - \`<fixed-agents>\` = \`${displayPath(L.fixedAgents)}\` — the shipped \`cohorte-review\`, \`cohorte-release\` and \`cohorte-profile-reader\` agents.`);
  out.push(`> - \`<workflows>\` = \`${displayPath(L.workflows)}\` — the shipped workflow scripts (\`cohorte-review.js\`, \`cohorte-audit.js\`, \`cohorte-refactor.js\`, \`cohorte-loop.js\`).`);
  out.push('> - Dispatch: the `Agent` tool (formerly `Task`), `subagent_type: <name>`.');
  out.push('> - **Gate** — `.claude/hooks/cohorte-gate.py` is committed in this repo and registered as a blocking `PreToolUse` hook in `.claude/settings.json`, reading `<state>/gate-config.json`. It fires whether or not you cooperate, and can deny outright or ask the human to confirm.');
  out.push(`> - \`<sync>\` = \`${sync}\` — wires THIS repo deterministically: copies the gate, registers its hook, writes the \`<state>/pipeline.json\` pointer, \`<state>/profile.json\` and the \`.gitignore\` entries. Re-run it after any edit to \`PIPELINE.md\`'s machine block. Run it from the repo root; never hand-write those files.`);
  return out.join('\n') + '\n';
}

function parseFrontmatter(text) {
  if (!text.startsWith('---\n')) return { keys: [], body: text };
  const end = text.indexOf('\n---\n', 3);
  if (end === -1) return { keys: [], body: text };
  const block = text.slice(4, end + 1);
  const body = text.slice(end + 5);
  const keys = [];
  for (const line of block.split('\n')) {
    const m = line.match(/^([A-Za-z][\w-]*):\s?(.*)$/);
    // Continuation lines (a wrapped value) belong to the previous key.
    if (!m) {
      if (line.trim() && keys.length) keys[keys.length - 1][1] += '\n' + line;
      continue;
    }
    keys.push([m[1], m[2]]);
  }
  return { keys, body };
}

function emitFrontmatter(keys) {
  if (!keys.length) return '';
  return '---\n' + keys.map(([k, v]) => `${k}: ${v}`).join('\n') + '\n---\n\n';
}

function render(source, L, allowed, kind) {
  const { keys, body } = parseFrontmatter(source);
  const kept = keys.filter(([k]) => allowed.includes(k));
  return emitFrontmatter(kept) + preamble(L, { kind }) + '\n' + body.replace(/^\n+/, '');
}

const renderCommand = (source, L) => render(source, L, COMMAND_KEYS, 'command');
const renderAgent = (source, L) => render(source, L, AGENT_KEYS, 'agent');

module.exports = {
  GATE_MATCHER,
  layout,
  displayPath,
  shellPath,
  preamble,
  parseFrontmatter,
  emitFrontmatter,
  renderCommand,
  renderAgent,
};
