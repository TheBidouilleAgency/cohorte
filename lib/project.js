#!/usr/bin/env node
'use strict';
// cohorte — wire ONE project, deterministically.
//
//   node <core>/lib/project.js sync   [root]   # copy the gate, register its hook, pointer, .gitignore,
//                                              # and .claude/profile.json (the parsed profile block)
//   node <core>/lib/project.js unsync [root]   # undo exactly what sync wrote
//
// Everything that describes a project lives in that project and is committed with it:
// PIPELINE.md, the surface agents, gate-config.json, the gate hook itself and its
// registration. The machine-wide install (`cohorte install`) only provides the commands
// and the generic core. A teammate who clones the repo therefore gets the gate even
// before installing Cohorte.
//
// This file is SELF-CONTAINED on purpose: the installer copies it to
// `~/.claude/cohorte/lib/project.js`, and `/cohorte-init-pipeline` runs it from there, so it
// must work without the `cohorte` binary on PATH (npx users). Its one sibling is `yaml.js` (the
// installer ships it next to this file), the same parser `cohorte doctor` uses — so sync and
// doctor cannot disagree about the profile. It is required lazily: a core missing it still wires
// the gate, and only `.claude/profile.json` is skipped, with a note saying why.

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const GATE_FILE = path.join('.claude', 'hooks', 'cohorte-gate.py');
const PROFILE_FILE = path.join('.claude', 'profile.json');
const GATE_COMMAND = 'python3 "$CLAUDE_PROJECT_DIR/.claude/hooks/cohorte-gate.py"';
const GATE_MATCHER = 'Bash|Task|Agent';
const EDIT_MATCHER = 'Write|Edit|MultiEdit';
const INSTALL_HINT = 'npm i -g cohorte && cohorte install';
const IGNORE_LINES = ['.claude/preflight.ok', '.claude/pipeline-metrics.jsonl', 'specs/reports/'];
const IGNORE_HEADER = '# cohorte — local-only pipeline artifacts (never commit these)';
const MARKERS = ['Generated by the cohorte adapter', 'Generated by the cohorte installer'];
const COMMIT_LIST = '.claude/settings.json, .claude/hooks/cohorte-gate.py, .claude/pipeline.json, .claude/profile.json and .gitignore';

// --- where the shipped assets are -------------------------------------------
// Installed:   <core>/lib/project.js, <core>/hooks/gate.py, <core>/pipeline/VERSION
// From source: <pkg>/lib/project.js, <pkg>/core/hooks/gate.py, <pkg>/package.json
function assets() {
  const up = path.join(__dirname, '..');
  const installed = fs.existsSync(path.join(up, 'pipeline', 'VERSION'));
  const coreDir = installed ? up : path.join(up, 'core');
  let version = null;
  try {
    version = installed
      ? fs.readFileSync(path.join(up, 'pipeline', 'VERSION'), 'utf8').trim()
      : JSON.parse(fs.readFileSync(path.join(up, 'package.json'), 'utf8')).version;
  } catch { /* reported by the caller */ }
  return {
    gate: path.join(coreDir, 'hooks', 'gate.py'),
    specTemplate: path.join(coreDir, 'templates', 'spec.template.md'),
    templatesDir: path.join(coreDir, 'templates'),
    version,
  };
}

// --- JSON that is never clobbered ---------------------------------------------
class ProjectError extends Error {}

// Read a JSON object file. Absent ⇒ {}. Present but unparseable ⇒ throw: a settings file
// with a trailing comma or a BOM used to be silently replaced by a fresh one, taking the
// user's model, env and permissions with it.
function readJsonObject(file) {
  let text;
  try { text = fs.readFileSync(file, 'utf8'); } catch (e) {
    if (e.code === 'ENOENT') return {};
    throw new ProjectError(`cannot read ${file}: ${e.message}`);
  }
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  if (!text.trim()) return {};
  let data;
  try { data = JSON.parse(text); } catch (e) {
    throw new ProjectError(`${file} is not valid JSON (${e.message}). Fix it and re-run — `
      + 'cohorte never rewrites a file it cannot parse.');
  }
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    throw new ProjectError(`${file} must contain a JSON object — leaving it untouched.`);
  }
  return data;
}

function writeIfChanged(file, content, changes, label) {
  let before = null;
  try { before = fs.readFileSync(file, 'utf8'); } catch { /* new file */ }
  if (before === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  changes.push(`${before === null ? 'created' : 'updated'} ${label}`);
  return true;
}

// --- the hook registration -----------------------------------------------------
// Ours: the 3.x command, or a 2.x registration of `.claude/hooks/gate.py` (what 2.x
// /cohorte-init-pipeline wrote: relative, $CLAUDE_PROJECT_DIR-anchored or absolute). Matching
// is on that exact path, never on a bare `gate.py` suffix — another tool's
// `~/tools/gate.py` is not ours to remove.
function isOurCommand(cmd) {
  if (typeof cmd !== 'string') return false;
  if (cmd.includes('cohorte-gate.py')) return true;
  return /(^|["'\s/])\.claude\/hooks\/gate\.py(["'\s]|$)/.test(cmd.replace(/\\/g, '/'));
}

// Remove our hook objects from every PreToolUse group; drop a group only when it ends up
// empty, so a user's own hook sharing a matcher group survives.
function stripOurHooks(list) {
  const out = [];
  let removed = 0;
  for (const group of Array.isArray(list) ? list : []) {
    if (!group || typeof group !== 'object' || !Array.isArray(group.hooks)) { out.push(group); continue; }
    const kept = group.hooks.filter((h) => !(h && isOurCommand(h.command)));
    removed += group.hooks.length - kept.length;
    if (kept.length) out.push(kept.length === group.hooks.length ? group : { ...group, hooks: kept });
  }
  return { list: out, removed };
}

function gateGroups() {
  const hook = { type: 'command', command: GATE_COMMAND, onFailure: 'block' };
  return [
    { matcher: GATE_MATCHER, hooks: [hook] },
    { matcher: EDIT_MATCHER, hooks: [{ ...hook }] },
  ];
}

// 2.x allowlisted the pipeline scripts at their old homes. Point them at the 3.x core.
function migratePermissions(data) {
  const allow = data.permissions && Array.isArray(data.permissions.allow) ? data.permissions.allow : null;
  if (!allow) return false;
  const next = [];
  for (const rule of allow) {
    let r = rule;
    if (typeof r === 'string') {
      r = r.replace('~/.claude/pipeline/scripts/', '~/.claude/cohorte/pipeline/scripts/');
      if (/\(\s*(bash\s+)?\.claude\/pipeline\/scripts\//.test(r)) continue; // bundled core is gone
    }
    if (!next.includes(r)) next.push(r);
  }
  if (next.length === allow.length && next.every((r, i) => r === allow[i])) return false;
  data.permissions.allow = next;
  return true;
}

// --- 2.x bundled-core cleanup ----------------------------------------------------
function gitTrackedClean(root, rel) {
  const r = spawnSync('git', ['-C', root, 'ls-files', '--error-unmatch', '--', rel], { stdio: 'ignore' });
  if (r.status !== 0) return false;
  const d = spawnSync('git', ['-C', root, 'diff', '--quiet', 'HEAD', '--', rel], { stdio: 'ignore' });
  return d.status === 0;
}

function hasMarker(file) {
  try { const t = fs.readFileSync(file, 'utf8'); return MARKERS.some((m) => t.includes(m)); } catch { return false; }
}

function walk(dir) {
  let out = [];
  let entries = [];
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    out = e.isDirectory() ? out.concat(walk(p)) : out.concat([p]);
  }
  return out;
}

// A 2.x "bundled" install vendored the whole core into <repo>/.claude. 3.x never does:
// remove what is provably ours. A file git tracks unmodified is simply deleted (git
// keeps it); anything else is moved to .claude/cohorte-legacy-backup/ for the human.
function legacyBundled(root, A) {
  const claude = path.join(root, '.claude');
  if (!fs.existsSync(path.join(claude, 'pipeline', 'VERSION'))) return [];
  const candidates = [];
  candidates.push(...walk(path.join(claude, 'pipeline')));
  for (const f of walk(path.join(claude, 'commands'))) {
    if (/cohorte-[\w-]+\.md$/.test(f) && hasMarker(f)) candidates.push(f);
  }
  for (const n of ['review', 'release', 'profile-reader']) {
    const f = path.join(claude, 'agents', `${n}.md`);
    if (fs.existsSync(f) && hasMarker(f)) candidates.push(f);
  }
  const shipped = new Set(walk(A.templatesDir).map((f) => path.relative(A.templatesDir, f)));
  for (const f of walk(path.join(claude, 'templates'))) {
    if (shipped.has(path.relative(path.join(claude, 'templates'), f))) candidates.push(f);
  }
  for (const n of ['review', 'audit', 'refactor', 'loop']) {
    const f = path.join(claude, 'workflows', `${n}.js`);
    try { if (/name:\s*'cohorte-/.test(fs.readFileSync(f, 'utf8'))) candidates.push(f); } catch { /* absent */ }
  }
  const gate = path.join(claude, 'hooks', 'gate.py');
  if (fs.existsSync(gate)) candidates.push(gate);

  const moved = [];
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  for (const f of candidates) {
    const rel = path.relative(root, f);
    if (gitTrackedClean(root, rel)) {
      fs.rmSync(f, { force: true });
      moved.push(`removed ${rel} (2.x bundled core — still in git history)`);
    } else {
      const dest = path.join(claude, 'cohorte-legacy-backup', stamp, path.relative(claude, f));
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.renameSync(f, dest);
      moved.push(`moved ${rel} → ${path.relative(root, dest)} (2.x bundled core, not tracked or modified)`);
    }
  }
  for (const d of ['pipeline', 'templates', 'workflows', 'commands', 'hooks']) pruneEmpty(path.join(claude, d));
  return moved;
}

function pruneEmpty(dir) {
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
  for (const e of entries) if (e.isDirectory()) pruneEmpty(path.join(dir, e.name));
  try { if (!fs.readdirSync(dir).length) fs.rmdirSync(dir); } catch { /* not empty */ }
}

// --- .gitignore -------------------------------------------------------------------
function ensureIgnored(root, changes) {
  const file = path.join(root, '.gitignore');
  let text = '';
  try { text = fs.readFileSync(file, 'utf8'); } catch { /* new */ }
  const have = new Set(text.split(/\r?\n/).map((l) => l.trim().replace(/^\/+/, '')));
  const missing = IGNORE_LINES.filter((l) => !have.has(l) && !have.has(l.replace(/\/$/, '')));
  if (!missing.length) return;
  const sep = text && !text.endsWith('\n') ? '\n' : '';
  const block = (text.includes(IGNORE_HEADER) ? '' : `${text ? '\n' : ''}${IGNORE_HEADER}\n`) + missing.join('\n') + '\n';
  fs.writeFileSync(file, text + sep + block);
  changes.push(`added ${missing.join(', ')} to .gitignore`);
}

// --- .claude/profile.json ----------------------------------------------------------
// The `yaml pipeline-profile` block of PIPELINE.md, parsed once here so every agent that needs only
// the machine block (implementers, the reviewer, the release agent, the workflows' profile-reader)
// reads a small JSON file instead of the whole profile. Committed, regenerated by every sync.
// Returns { text } to write, or { note } saying why nothing was written.
function profileJson(root) {
  let md;
  try { md = fs.readFileSync(path.join(root, 'PIPELINE.md'), 'utf8'); } catch {
    return { note: 'PIPELINE.md not found — .claude/profile.json not written (run /cohorte-init-pipeline)' };
  }
  let yaml;
  try { yaml = require('./yaml.js'); } catch {
    return { note: `yaml.js missing next to ${__filename} — .claude/profile.json not written (reinstall cohorte)` };
  }
  let text = null;
  try { text = yaml.profileJsonText(md); } catch { /* reported below */ }
  if (!text) {
    return { note: 'PIPELINE.md has no parseable `yaml pipeline-profile` block — .claude/profile.json not written'
      + (fs.existsSync(path.join(root, PROFILE_FILE)) ? ' (the existing one was left as is and may be stale)' : '') };
  }
  return { text };
}

// --- sync / unsync -----------------------------------------------------------------
function sync(rootArg) {
  const root = path.resolve(rootArg || process.cwd());
  if (!fs.statSync(root).isDirectory()) throw new ProjectError(`${root} is not a directory`);
  const A = assets();
  if (!fs.existsSync(A.gate)) throw new ProjectError(`gate hook not found at ${A.gate} — reinstall cohorte`);
  const changes = [];
  const notes = [];

  // Parse everything we will touch BEFORE writing anything: an invalid file aborts the
  // whole sync rather than leaving the project half-wired.
  const settingsPath = path.join(root, '.claude', 'settings.json');
  const pointerPath = path.join(root, '.claude', 'pipeline.json');
  const settings = readJsonObject(settingsPath);
  const pointer = readJsonObject(pointerPath);

  changes.push(...legacyBundled(root, A));

  // 1. The gate itself, committed with the repo.
  const gateText = fs.readFileSync(A.gate, 'utf8');
  if (writeIfChanged(path.join(root, GATE_FILE), gateText, changes, GATE_FILE) && process.platform !== 'win32') {
    try { fs.chmodSync(path.join(root, GATE_FILE), 0o755); } catch { /* optional */ }
  }

  // 2. Its registration — exactly one of ours, every foreign hook untouched.
  if (!settings.hooks || typeof settings.hooks !== 'object' || Array.isArray(settings.hooks)) settings.hooks = {};
  const { list } = stripOurHooks(settings.hooks.PreToolUse);
  settings.hooks.PreToolUse = list.concat(gateGroups());
  migratePermissions(settings);
  writeIfChanged(settingsPath, JSON.stringify(settings, null, 2) + '\n', changes, '.claude/settings.json (gate hook)');

  // 3. The pointer: tells a teammate (and /cohorte-doctor) which core this repo expects.
  delete pointer.mode; // 3.x has a single mode
  Object.assign(pointer, { pipeline: 'cohorte', core_version: A.version, install: INSTALL_HINT });
  writeIfChanged(pointerPath, JSON.stringify(pointer, null, 2) + '\n', changes, '.claude/pipeline.json');

  // 4. Local-only artifacts stay out of git.
  ensureIgnored(root, changes);

  // 5. The spec template /cohorte-spec copies from.
  const specTpl = path.join(root, 'specs', '_template.md');
  if (!fs.existsSync(specTpl) && fs.existsSync(A.specTemplate)) {
    fs.mkdirSync(path.dirname(specTpl), { recursive: true });
    fs.copyFileSync(A.specTemplate, specTpl);
    changes.push('created specs/_template.md');
  }

  // 6. The parsed profile block, for agents that need only the machine block. Written AFTER
  //    PIPELINE.md: every command that edits the block re-runs sync so this file follows it.
  const pj = profileJson(root);
  if (pj.text) writeIfChanged(path.join(root, PROFILE_FILE), pj.text, changes, '.claude/profile.json');
  else notes.push(pj.note);
  return { root, version: A.version, changes, notes };
}

function unsync(rootArg) {
  const root = path.resolve(rootArg || process.cwd());
  const changes = [];
  const settingsPath = path.join(root, '.claude', 'settings.json');
  const settings = readJsonObject(settingsPath);
  if (settings.hooks && Array.isArray(settings.hooks.PreToolUse)) {
    const { list, removed } = stripOurHooks(settings.hooks.PreToolUse);
    if (removed) {
      if (list.length) settings.hooks.PreToolUse = list; else delete settings.hooks.PreToolUse;
      if (!Object.keys(settings.hooks).length) delete settings.hooks;
      fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 2) + '\n');
      changes.push(`removed ${removed} gate hook registration(s) from .claude/settings.json`);
    }
  }
  for (const rel of [GATE_FILE, path.join('.claude', 'pipeline.json'), PROFILE_FILE]) {
    if (fs.existsSync(path.join(root, rel))) { fs.rmSync(path.join(root, rel)); changes.push(`removed ${rel}`); }
  }
  pruneEmpty(path.join(root, '.claude', 'hooks'));
  const left = ['PIPELINE.md', '.claude/gate-config.json', '.claude/agents', 'specs', 'scripts/new-feature.sh',
    'scripts/remove-feature.sh'].filter((p) => fs.existsSync(path.join(root, p)));
  return { root, changes, left };
}

module.exports = { sync, unsync, readJsonObject, stripOurHooks, isOurCommand, ProjectError, profileJson,
  GATE_COMMAND, GATE_MATCHER, EDIT_MATCHER, GATE_FILE, PROFILE_FILE, IGNORE_LINES, COMMIT_LIST };

// --- CLI -----------------------------------------------------------------------------
if (require.main === module) {
  const [verb, root] = process.argv.slice(2);
  try {
    if (verb === 'sync') {
      const r = sync(root);
      console.log(`cohorte sync — ${r.root} (core ${r.version})`);
      for (const c of r.changes) console.log(`  · ${c}`);
      if (!r.changes.length) console.log('  · already in sync');
      for (const n of r.notes) console.log(`  ! ${n}`);
      if (r.changes.length) console.log(`  Commit ${COMMIT_LIST}.`);
    } else if (verb === 'unsync') {
      const r = unsync(root);
      for (const c of r.changes) console.log(`  · ${c}`);
      if (r.left.length) console.log(`  Project files kept (yours to delete): ${r.left.join(', ')}`);
    } else {
      console.error('usage: project.js sync|unsync [root]');
      process.exit(2);
    }
  } catch (e) {
    console.error(`error: ${e.message}`);
    process.exit(1);
  }
}
